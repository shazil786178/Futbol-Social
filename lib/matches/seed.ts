export function getSeedMatch(id: string): Match | undefined {
  return SEED_MATCHES.find((match) => match.id === id);
}

export function getSeedHighlights(matchId?: string): Highlight[] {
  if (!matchId) return SEED_HIGHLIGHTS;
  return SEED_HIGHLIGHTS.filter((h) => h.matchId === matchId);
}

export function getSeedSkits(): Skit[] {
  return SEED_SKITS;
}

export function getDefaultLiveMatch(): Match | undefined {
  return SEED_MATCHES.map(withResolvedStatus).find((m) => m.status === "live");
}

